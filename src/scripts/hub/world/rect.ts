// Rect tests shared by the page model and the scenes. Kept apart from geom.ts so the
// eager chrome bundle does not pull in the scene-only geometry helpers.

import type { Rect } from "./types";

export function rectDistance(px: number, py: number, r: Rect): number {
  const dx = Math.max(r.x - px, 0, px - (r.x + r.w));
  const dy = Math.max(r.y - py, 0, py - (r.y + r.h));
  return Math.hypot(dx, dy);
}

/** True when (x, y) lies inside r grown by pad on every side (a negative pad shrinks it). */
export function pointInRect(r: Rect, x: number, y: number, pad = 0): boolean {
  return x >= r.x - pad && x <= r.x + r.w + pad && y >= r.y - pad && y <= r.y + r.h + pad;
}

/** True when the two rects share interior area. */
export function rectsIntersect(a: Rect, b: Rect): boolean {
  return a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h;
}

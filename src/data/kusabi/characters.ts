// The character book. PUBLIC_CARDS go in the page's HTML and may only hold what
// the opening chapters establish. Everything else is served from the vault after
// its unlock (vault.ts), and is written from work/drafts/, with chapter:line
// references here so the next edit can be checked. Age, university year and height
// come from kb/characters/cast_biography.md because the chapters never state them.

/** One row of a file. With no value it is drawn empty until a later tier fills it. */
export interface CharacterField {
  label: string;
  value?: string;
}

export interface CharacterCard {
  id: string;
  name: string;
  role: string;
  note: string;
  /** Neutral file under /assets/kusabi/images/. */
  image?: string;
  fields?: CharacterField[];
}

/** What a finished chapter changes on a file that is already open. */
export interface CharacterUpdate {
  card: string;
  /** Replaces the name on the strip. */
  name?: string;
  /** Replaces the role line. */
  role?: string;
  /** Replaces the whole bio, so it always reads as what the reader knows by now. */
  note?: string;
  /** Fills a row by label, or adds the row if the file does not have it yet. */
  fields?: CharacterField[];
}

export interface CharacterNote {
  card: string;
  text: string;
  /** Written the way the notebook in CH11 writes it: a word struck through or in pen. */
  pen?: boolean;
  /** A line the notebook has struck out; no words are shown. */
  struck?: boolean;
}

export interface CharacterTier {
  cards?: Array<CharacterCard & { replaces?: string[]; extraFrame?: boolean }>;
  updates?: CharacterUpdate[];
  notes?: CharacterNote[];
  /** After CH11 the guest book turns out to be someone's notebook. */
  book?: "behaviour";
}

